it("preserves newer typing across its own delayed URL acknowledgement and rapid filters", () => {
  const { result, rerender } = renderHook(({ query }) => useArchiveContext(new URLSearchParams(query), ""), { initialProps: { query: "q=first&id=a" } })
  act(() => result.current.setSearch("committed"))
  act(() => vi.advanceTimersByTime(300))
  act(() => result.current.setSearch("newer draft"))
  rerender({ query: "q=committed&id=a" })
  expect(result.current.context.filter.search).toBe("newer draft")
  act(() => { result.current.setLibraryId("work"); result.current.updateFilter(f => ({ ...f, sortBy: "completion" })) })
  expect(window.location.search).toBe("?lib=work&q=newer+draft&sort=completion&id=a")
  // Intermediate acknowledgements must not overwrite the newer filter either.
  rerender({ query: "lib=work&q=newer+draft&id=a" })
  expect(result.current.context.filter.sortBy).toBe("completion")
  rerender({ query: "lib=work&q=newer+draft&sort=completion&id=a" })
  act(() => vi.advanceTimersByTime(300))
  expect(result.current.context.filter).toMatchObject({ search: "newer draft", sortBy: "completion" })
})
