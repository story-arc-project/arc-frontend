it("lets Next's native-history wrapper publish updated search parameters", () => {
  // Next bypasses its URL subscription when callers pass its internal __NA
  // marker. Its wrapper copies that marker itself for ordinary native writes.
  window.history.replaceState({ __NA: true, tree: "router-owned" }, "", "/archive?q=first&id=a")
  const original = window.history.replaceState.bind(window.history)
  let publishedQuery = "q=first&id=a"
  vi.spyOn(window.history, "replaceState").mockImplementation((state, title, url) => {
    original(state, title, url)
    if (!state?.__NA && !state?._N) publishedQuery = window.location.search.slice(1)
  })
  const { result } = renderHook(() => useArchiveContext(new URLSearchParams("q=first&id=a"), ""))
  act(() => result.current.setSearch("published"))
  act(() => vi.advanceTimersByTime(300))
  expect(publishedQuery).toBe("q=published&id=a")
  vi.restoreAllMocks()
})
