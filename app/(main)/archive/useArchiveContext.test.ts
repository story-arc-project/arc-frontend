it("retained href after unmount leaves the destination history untouched", () => {
  const { result, unmount } = renderHook(() => useArchiveContext(new URLSearchParams("q=first&id=a"), ""))
  act(() => result.current.setSearch("pending"))
  const finish = result.current.href
  unmount()
  window.history.pushState({ destination: true }, "", "/dashboard?q=destination&id=other")
  expect(finish("copy")).toBe("/archive?q=pending&id=copy")
  act(() => vi.advanceTimersByTime(300))
  expect(window.location.pathname + window.location.search).toBe("/dashboard?q=destination&id=other")
  expect(window.history.state).toEqual({ destination: true })
})
